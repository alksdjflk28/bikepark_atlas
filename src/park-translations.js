export function pt(park, field) {
  // Eigene Übersetzung direkt am Park (z. B. über den Editor ergänzt) hat Vorrang.
  const own = park.i18n?.[currentLang]?.[field]
  if (own) return own

  const translations = PARK_TRANSLATIONS[park.id]
  if (!translations) return park[field]
  const langTranslations = translations[currentLang]
  if (!langTranslations) return park[field]
  return langTranslations[field] || park[field]
}

export function ptPrice(price, lang) {
  // price.note can be translated via PARK_TRANSLATIONS[parkId].priceNote
  // This is handled in pt() with field 'priceNote'
  return price
}


